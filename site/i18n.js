  const DICTS = { vi: VI };
  const LETTER = /[A-Za-z]/;
  const NUM = "([−+\\-]?(?:\\d[\\d.,:]*|—))";
  // A named capture stays inside one sentence and one part: it never
  // crosses ". ", "? ", "! ", " · " or " — ".
  const TEXT = "((?:(?![.!]\\s|\\?\\s+[A-Z][a-z])[^·—])+?)";
  const cache = {};

  function norm(s) { return String(s).replace(/\s+/g, " ").trim(); }
  function escapeRe(s) { return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"); }

  function compile(lang) {
    if (cache[lang]) return cache[lang];
    const d = DICTS[lang] || {}, exact = new Map(), pats = [];
    for (const k of Object.keys(d)) {
      const key = norm(k);
      if (/\{\w+\}/.test(key)) {
        const names = [];
        const src = key.split(/(\{\w+\})/).map((part) => {
          const m = /^\{(\w+)\}$/.exec(part);
          if (!m) return escapeRe(part);
          names.push(m[1]);
          return /^\d$/.test(m[1]) ? NUM : TEXT;
        }).join("");
        pats.push({ re: new RegExp("^" + src + "$"), names, out: d[k], lit: key.replace(/\{\w+\}/g, "").length });
      } else exact.set(key, d[k]);
    }
    // The most specific pattern first: the one with the most fixed text.
    pats.sort((a, b) => b.lit - a.lit);
    return (cache[lang] = { exact, pats });
  }

  /** One text: an exact key, else the first pattern that matches, else null. */
  function one(s, c, depth, misses) {
    if (c.exact.has(s)) return c.exact.get(s);
    for (const p of c.pats) {
      const m = p.re.exec(s);
      if (!m) continue;
      const vals = {};
      p.names.forEach((n, i) => {
        const v = m[i + 1];
        let t = null;
        if (!/^\d$/.test(n) && LETTER.test(v)) {
          t = depth < 1 ? one(v, c, depth + 1, null) : null;
          if (t == null && misses) misses.push(v);
        }
        vals[n] = t == null ? v : t;
      });
      return p.out.replace(/\{(\w+)\}/g, (x, n) => (Object.prototype.hasOwnProperty.call(vals, n) ? vals[n] : x));
    }
    return null;
  }

  /** The sentences of one part: split after ". ", "? " or "! ". */
  function sentences(s) { return s.replace(/([.!?])\s+(?=\S)/g, "$1\n").split("\n"); }

  function run(text, lang, misses) {
    const s = String(text);
    if (!lang || lang === "en" || !DICTS[lang]) return s;
    const n = norm(s);
    if (!LETTER.test(n)) return s;
    const c = compile(lang);
    const lead = /^\s*/.exec(s)[0], trail = /\s*$/.exec(s)[0];
    let r = one(n, c, 0, misses);
    if (r == null) {
      const parts = n.split(/(\s*·\s*|\s+—\s+)/);
      r = parts.map((part, i) => {
        if (i % 2 || !LETTER.test(part)) return part;
        const whole = one(part, c, 0, misses);
        if (whole != null) return whole;
        return sentences(part).map((x) => {
          if (!LETTER.test(x)) return x;
          const t = one(x, c, 0, misses);
          if (t == null) { if (misses) misses.push(x); return x; }
          return t;
        }).join(" ");
      }).join("");
    }
    return lead + r + trail;
  }

  function translate(text, lang) { return run(text, lang, null); }
  function report(text, lang) { const m = []; run(text, lang, m); return m; }
  function entries(lang) { return Object.entries(DICTS[lang] || {}); }

  const api = { LANGS, translate, report, entries };
  if (typeof module !== "undefined" && module.exports) module.exports = api;
  else root.CalibI18n = api;
